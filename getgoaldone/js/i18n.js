const LANGUAGES = [
  { id: "en", label: "English", voice: "en-US" },
  { id: "es", label: "Español", voice: "es-ES" },
];

let language = detectLanguage();

function detectLanguage() {
  const browser = (navigator.language || "en").slice(0, 2).toLowerCase();
  return STRINGS[browser] ? browser : "en";
}

function setLanguage(id) {
  if (STRINGS[id]) {
    language = id;
  }
}

// t("hud.kickoff", { team: "Reds" }) -> "⚽ Reds kick off"
function t(key, params) {
  let text = STRINGS[language][key] ?? STRINGS.en[key] ?? key;
  if (params) {
    for (const name in params) {
      text = text.split("{" + name + "}").join(params[name]);
    }
  }
  return text;
}

function voiceLanguage() {
  return LANGUAGES.find(lang => lang.id === language).voice;
}
